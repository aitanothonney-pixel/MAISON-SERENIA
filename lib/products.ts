// (ex. 215 → 236,50 → 239 ; 499 → 548,90 → 549 ; 136 → 149,60 → 149).
function bumpPrice(price: number): number {
  const raised = price * 1.1;
  const rounded = Math.round((raised - 9) / 10) * 10 + 9;
  return Math.max(9, rounded);
}

